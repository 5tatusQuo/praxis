# Lifecycle states that are deployed. Drafts and deprecated rules are not.
DEPLOYED_LIFECYCLES = ("staged", "production")


def load_repo(root: Path | None = None) -> ContentRepo:
    return ContentRepo(root or get_settings().content_dir, implementation_files())


def _validate_visibility_content(repo: ContentRepo) -> list[Issue]:
    issues = []
    components = set(attack.bundle()["data_components"])
    for (platform, source), note in repo.datamap.items():
        path = repo.root / "datamap-catalog" / platform / f"{source}.md"
        for component in note.data_components:
            if component not in components:
                issues.append(Issue(path, f"unknown ATT&CK data component {component!r}"))
    groups = attack.bundle()["groups"]
    for sector, profile in repo.threat_profiles.items():
        path = repo.root / "threat-profiles" / f"{sector}.yml"
        issues.extend(
            Issue(path, f"{g} is not an ATT&CK group") for g in profile.groups if g not in groups
        )
        issues.extend(
            Issue(path, f"{t} is not in ATT&CK")
            for t in profile.techniques
            if not attack.is_technique(t)
        )
    for client_id, telemetry in repo.lab_telemetry.items():
        path = repo.root / "clients" / client_id / "lab" / "telemetry.yml"
        client = repo.clients.get(client_id)
        for spec in telemetry.sources:
            for platform in client.platforms.enabled() if client else []:
                if (platform, spec.source) not in repo.datamap:
                    issues.append(Issue(path, f"no datamap-catalog note for {spec.source}"))
    return issues


def validate(repo: ContentRepo) -> list[Issue]:
    """Schema, references, ATT&CK ids, README template and per-platform checks."""
    issues = list(repo.issues) + _validate_visibility_content(repo)
    for bundle in repo.detections.values():
        meta_path = bundle.path / "detection.yml"
        for ref in bundle.meta.attack:
            if not attack.is_technique(ref.technique):
                issues.append(Issue(meta_path, f"{ref.technique} is not in ATT&CK"))
            elif not attack.is_tactic(ref.tactic):
                issues.append(Issue(meta_path, f"{ref.tactic} is not an ATT&CK tactic"))
            elif ref.tactic not in attack.technique_tactics(ref.technique):
                issues.append(
                    Issue(meta_path, f"{ref.technique} does not belong to tactic {ref.tactic}")
                )
        known = set(attack.bundle()["data_components"])
        for component in bundle.meta.data_components:
            if component not in known:
                issues.append(Issue(meta_path, f"unknown ATT&CK data component {component!r}"))
        if bundle.readme:
            issues.extend(
                Issue(bundle.path / "README.md", p) for p in lint_readme(bundle.readme, bundle.id)
            )
        for platform_name, impl in bundle.implementations.items():
            if platform_name in bundle.meta.log_sources:
                issues.extend(
                    Issue(impl.path, p) for p in get_platform(platform_name).check(bundle)
                )
    for client in repo.clients.values():
        for bundle in repo.detections_for(client):
            if not any(p in bundle.implementations for p in client.platforms.enabled()):
                issues.append(
                    Issue(
                        repo.root / "clients" / client.id / "client.yml",
                        f"{bundle.id} has no implementation for this client's platforms",
                    )
                )
    return issues


def deployable(bundle: DetectionBundle) -> bool:
    return bundle.meta.lifecycle in DEPLOYED_LIFECYCLES


def render_client(repo: ContentRepo, client: Client, platform_name: str) -> list[RenderedRule]:
    """Every deployable rule for one client on one platform."""
    platform = get_platform(platform_name)
    return [
        platform.render(bundle, client, repo.tuning_for(bundle.id, client, platform_name))
        for bundle in repo.detections_for(client)
        if deployable(bundle) and platform_name in bundle.implementations
    ]


# -- packs.lock ---------------------------------------------------------------
LOCK_NAME = "packs.lock"
_LOCK_HEADER = "# Generated by `praxis lock`. Do not edit: CI checks it and CD deploys only this.\n"


def build_lock(repo: ContentRepo, client: Client) -> dict:
    """The exact detection versions, tuning and content hashes a client runs."""
    platforms: dict[str, dict] = {}
    for platform_name in client.platforms.enabled():
        platforms[platform_name] = {
            rule.detection_id: {
                "version": rule.version,
                "hash": rule.content_hash,
                "tuning": rule.tuning_digest,
            }
            for rule in render_client(repo, client, platform_name)
        }
    return {"client": client.id, "platforms": platforms}


def lock_path(repo: ContentRepo, client: Client) -> Path:
    return repo.root / "clients" / client.id / LOCK_NAME


def write_lock(repo: ContentRepo, client: Client) -> Path:
    path = lock_path(repo, client)
    path.write_text(_LOCK_HEADER + yaml.safe_dump(build_lock(repo, client), sort_keys=True))
    return path


def lock_is_current(repo: ContentRepo, client: Client) -> bool:
    path = lock_path(repo, client)
    return path.is_file() and yaml.safe_load(path.read_text()) == build_lock(repo, client)


# -- lab ------------------------------------------------------------------------
def lab_test(repo: ContentRepo, bundle: DetectionBundle) -> list[CaseResult]:
    """Replay a detection's events in the lab SIEM of every platform it has.

    Base cases: positives fire, negatives stay quiet. Then, for every client
    that tunes this detection: positives must still fire with the tuning (the
    over-tuning guard), and each tuning example must fire untuned and stay
    quiet tuned (the tune does what it claims, and is needed).
    """
    results: list[CaseResult] = []
    for platform_name in bundle.implementations:
        platform = get_platform(platform_name)

        def run(name, scope, events, tuning, expected, platform=platform):
            fired, error = False, None
            try:
                fired = platform.lab_fires(bundle, events, tuning)
            except Exception as err:  # a broken query or lab must fail the case, not crash
                error = str(err)[:400]
            results.append(
                CaseResult(bundle.id, platform.name, name, scope, expected, fired, error)
            )

        for case in bundle.positive:
            run(case.name, "base", case.events, None, True)
        for case in bundle.negative:
            run(case.name, "base", case.events, None, False)
        for client in repo.clients.values():
            if not platform.supports(client) or bundle not in repo.detections_for(client):
                continue
            tuning = repo.tuning_for(bundle.id, client, platform_name)
            if not tuning.exclude:
                continue
            for case in bundle.positive:
                run(f"{case.name} (tuned)", client.id, case.events, tuning, True)
            examples = repo.tuning_examples(bundle.id, client, platform_name)
            for number, event in enumerate(examples, start=1):
                run(f"tuning example {number} (untuned)", client.id, [event], None, True)
                run(f"tuning example {number} (tuned)", client.id, [event], tuning, False)
    return results


def _git(args: list[str], cwd: Path) -> str | None:
    result = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    return result.stdout if result.returncode == 0 else None


def docs_follow_queries(repo: ContentRepo, base: str) -> list[Issue]:
    """A query change must come with a change to the README's 'How it works'."""
    issues = []
    top = _git(["rev-parse", "--show-toplevel"], repo.root)
    if top is None:
        return [Issue(repo.root, "not inside a git repository")]
    top_path = Path(top.strip())
    for bundle in repo.detections.values():
        old_readme = _git(
            ["show", f"{base}:{(bundle.path / 'README.md').relative_to(top_path)}"], top_path
        )
        if old_readme is None:
            continue  # new detection
        for impl in bundle.implementations.values():
            old_query = _git(["show", f"{base}:{impl.path.relative_to(top_path)}"], top_path)
            if old_query is None or old_query.strip() == impl.query:
                continue
            if section(old_readme, "How it works") == section(bundle.readme, "How it works"):
                issues.append(
                    Issue(
                        impl.path,
                        "query changed but README 'How it works' did not; update the docs",
                    )
                )
    return issues


# -- visibility and gaps ---------------------------------------------------------
def collect(repo: ContentRepo, client: Client) -> Inventory:
    """Run the read-only collectors for every platform the client has."""
    from datetime import UTC, datetime

    sources, rules = [], []
    for platform_name in client.platforms.enabled():
        platform = get_platform(platform_name)
        fields = {
            source: sorted({f for names in note.data_components.values() for f in names})
            for (note_platform, source), note in repo.datamap.items()
            if note_platform == platform_name
        }
        sources += platform.collect_sources(client, fields)
        rules += platform.collect_rules(client)
    taken_at = datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    return Inventory(client=client.id, taken_at=taken_at, sources=sources, rules=rules)


def coverage(repo: ContentRepo, client: Client) -> tuple[Inventory, dict]:
    """Collect, then run the gap engine. Returns the raw inventory and the snapshot."""
    inventory = collect(repo, client)
    return inventory, build_snapshot(repo, client, inventory)


def datamap_csv(inventory: Inventory) -> str:
    """clients/<id>/datamap/tables.csv: which tables a client has, and how busy they are."""
    lines = ["platform,table,source,events_14d,hosts,last_event"]
    for s in inventory.sources:
        lines.append(
            f"{s.platform},{s.table},{s.source},{s.events_14d},{s.hosts},{s.last_event or ''}"
        )
    return "\n".join(lines) + "\n"


def drift(repo: ContentRepo, client: Client) -> list[str]:
    """Differences between what packs.lock pins and what the SIEM runs."""
    problems = []
    lock = build_lock(repo, client)["platforms"]
    for platform_name in client.platforms.enabled():
        deployed = {r.detection_id: r for r in get_platform(platform_name).collect_rules(client)}
        for rule_id, pinned in lock[platform_name].items():
            health = deployed.pop(rule_id, None)
            if health is None:
                problems.append(f"{platform_name}: {rule_id} is pinned but not deployed")
            elif health.deployed_hash != pinned["hash"][:16]:
                problems.append(f"{platform_name}: {rule_id} differs from packs.lock")
        problems += [f"{platform_name}: {r} is deployed but not pinned" for r in deployed]
    return problems


def expiring(repo: ContentRepo, within_days: int) -> list[dict]:
    """Tuning files and detections past their `expires` date, or close to it."""
    from datetime import date, timedelta

    today = date.today()
    horizon = today + timedelta(days=within_days)
    items = [
        (f"clients/{client_id}/tuning/{rule}.yml", tuning.expires)
        for (client_id, rule), tuning in repo.client_tuning.items()
    ]
    items += [
        (f"overlays/platform/{platform}/{rule}.yml", tuning.expires)
        for (platform, rule), tuning in repo.platform_overlays.items()
    ]
    items += [(f"detections/{b.path.name}", b.meta.expires) for b in repo.detections.values()]
    return [
        {"item": item, "expires": when.isoformat(), "expired": when < today}
        for item, when in sorted(items, key=lambda i: str(i[1]))
        if when is not None and when <= horizon
    ]
